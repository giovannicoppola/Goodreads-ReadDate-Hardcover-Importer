"""Sync Goodreads reading dates with Hardcover.

Usage:
  sync_hardcover.py <tsv_file> [--api-key=<file>] [--limit=<n>] [--delay=<seconds>] [--log] [--dry-run] [--help]
  sync_hardcover.py (-h | --help)

Options:
  <tsv_file>          Path to the TSV file generated by parse_goodreads.py
  --api-key=<file>    Path to the JSON file containing the Hardcover API key [default: hardcover_api_key.json]
  --limit=<n>         Maximum number of books to process (useful for testing) [default: 0]
  --delay=<seconds>   Seconds to wait between books [default: 1]
  --log               Generate a log.txt file with all output
  --dry-run           Show what would change without writing anything to Hardcover
  -h --help           Show this help message and exit

Examples:
  sync_hardcover.py books.tsv
  sync_hardcover.py books.tsv --api-key=my_api_key.json
  sync_hardcover.py books.tsv --limit=5      # Process only 5 books
  sync_hardcover.py books.tsv --dry-run      # Preview changes only
  sync_hardcover.py books.tsv --log          # Generate log file
"""

import csv
import json
import sys
import time
from datetime import datetime

import requests
from docopt import docopt

# HTTP statuses that are worth retrying: gateway/availability hiccups and
# rate limiting.
RETRYABLE_STATUS_CODES = frozenset({429, 500, 502, 503, 504})

REQUIRED_COLUMNS = ("Goodreads ID", "Book Title", "Date Started", "Date Read")


class Logger:
    """Handles logging to both console and file."""

    def __init__(self, log_to_file=False):
        self.log_to_file = log_to_file
        self.log_file = None
        if log_to_file:
            self.log_file = open("log.txt", "w", encoding="utf-8")
            self._write_log_header()

    def _write_log_header(self):
        """Write the log file header."""
        if self.log_file:
            timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            self.log_file.write("=" * 80 + "\n")
            self.log_file.write("Hardcover Goodreads Reading Dates Updater\n")
            self.log_file.write(f"Started at: {timestamp}\n")
            self.log_file.write("=" * 80 + "\n\n")

    def log(self, message):
        """Log a message to both console and file if logging is enabled."""
        print(message)
        if self.log_file:
            self.log_file.write(message + "\n")
            self.log_file.flush()

    def close(self):
        """Close the log file if it's open."""
        if self.log_file:
            self.log_file.write("\n" + "=" * 80 + "\n")
            self.log_file.write(
                f"Log completed at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
            )
            self.log_file.write("=" * 80 + "\n")
            self.log_file.close()
            self.log_file = None

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        self.close()
        return False


class HardcoverClient:
    """Client for interacting with the Hardcover API."""

    def __init__(
        self,
        api_key,
        api_url="https://api.hardcover.app/v1/graphql",
        logger=None,
        dry_run=False,
        timeout=30,
    ):
        self.logger = logger or Logger()
        self.logger.log("\nInitializing HardcoverClient...")
        self.api_key = normalize_api_key(api_key)
        self.api_url = api_url
        self.dry_run = dry_run
        self.timeout = timeout
        self.headers = {
            "Content-Type": "application/json",
            "Authorization": self.api_key,
        }
        self.user_id = None  # Cache for user ID
        self.max_retries = 3  # Maximum number of attempts for retryable errors
        self.base_delay = 2  # Base delay in seconds for exponential backoff

    def log(self, message):
        """Log a message using the logger."""
        self.logger.log(message)

    def _make_request_with_retry(self, query, variables=None):
        """POST a GraphQL request, retrying transient failures.

        Returns (payload, True) on success, where payload is the decoded JSON
        body, or (None, False) if the request could not be completed.
        """
        request_data = {"query": query}
        if variables:
            request_data["variables"] = variables

        for attempt in range(1, self.max_retries + 1):
            try:
                response = requests.post(
                    self.api_url,
                    json=request_data,
                    headers=self.headers,
                    timeout=self.timeout,
                )
            except requests.exceptions.RequestException as e:
                if attempt < self.max_retries:
                    delay = self.base_delay * (2 ** (attempt - 1))
                    self.log(
                        f"⚠️ Network error: {e}. Retrying in {delay} seconds... "
                        f"(Attempt {attempt}/{self.max_retries})"
                    )
                    time.sleep(delay)
                    continue
                self.log(f"❌ Network error after {self.max_retries} attempts: {e}")
                return None, False

            if response.status_code in RETRYABLE_STATUS_CODES:
                if attempt < self.max_retries:
                    delay = self.base_delay * (2 ** (attempt - 1))
                    if response.status_code == 429:
                        # Honour Retry-After when the API sends one.
                        delay = max(delay, _retry_after_seconds(response, delay))
                    self.log(
                        f"⚠️ API Error {response.status_code}. Retrying in {delay} seconds... "
                        f"(Attempt {attempt}/{self.max_retries})"
                    )
                    time.sleep(delay)
                    continue
                self.log(
                    f"❌ Maximum retry attempts reached for HTTP {response.status_code}"
                )
                return None, False

            if response.status_code != 200:
                self.log(f"❌ API Error: HTTP {response.status_code}")
                self.log(f"Response: {response.text[:500]}")
                return None, False

            try:
                payload = response.json()
            except ValueError:
                self.log("❌ API returned a non-JSON response")
                self.log(f"Response: {response.text[:500]}")
                return None, False

            if payload.get("errors"):
                self.log(f"❌ GraphQL errors: {payload['errors']}")
                return None, False

            return payload, True

        return None, False

    def get_user_id(self):
        """Fetch the user ID from the Hardcover API."""
        if self.user_id is not None:
            return self.user_id

        self.log("\nGetting user ID...")
        query = """
        query {
          me {
            id
          }
        }
        """
        payload, success = self._make_request_with_retry(query)
        if not success:
            return None

        me = (payload.get("data") or {}).get("me") or []
        if me and isinstance(me, list) and me[0].get("id") is not None:
            self.user_id = me[0]["id"]
            self.log(f"User ID fetched: {self.user_id}")
            return self.user_id

        self.log("Error: Could not fetch user ID from response.")
        self.log("Check that your API key is valid and includes the 'Bearer ' prefix.")
        self.log(f"Response: {payload}")
        return None

    def find_book_by_goodreads_id(self, goodreads_id, date_finished=None):
        """Find the reading journey for a book, using its Goodreads ID.

        Returns a dict with journey_id/started_at/finished_at, or None when the
        book (or a journey for it) cannot be found.
        """
        user_id = self.get_user_id()
        if not user_id:
            return None

        query = """
        query FindBookByGoodreadsId($goodreadsId: String!, $userId: Int!) {
          book_mappings(where: {external_id: {_eq: $goodreadsId}}) {
            id
            book_id
            platform_id
            book {
              user_books(where: {user_id: {_eq: $userId}}) {
                id
                user_book_reads {
                  id
                  started_at
                  finished_at
                }
              }
            }
          }
        }
        """

        variables = {"goodreadsId": str(goodreads_id), "userId": int(user_id)}
        payload, success = self._make_request_with_retry(query, variables)
        if not success:
            return None

        mappings = (payload.get("data") or {}).get("book_mappings") or []
        if not mappings:
            self.log(f"  ℹ️ No Hardcover book is mapped to Goodreads ID {goodreads_id}")
            return None

        # A Goodreads ID can be mapped to more than one Hardcover edition; use
        # the first mapping that the user actually has on a shelf.
        journeys = []
        for mapping in mappings:
            for user_book in ((mapping.get("book") or {}).get("user_books") or []):
                journeys.extend(user_book.get("user_book_reads") or [])
            if journeys:
                break

        if not journeys:
            self.log("  ℹ️ Book found on Hardcover but no reading journey exists for it")
            return None

        chosen = journeys[0]
        if len(journeys) > 1:
            self.log(f"  ⚠️ Multiple journeys found ({len(journeys)})")
            match = next(
                (j for j in journeys if j.get("finished_at") == date_finished), None
            )
            if match is not None:
                self.log(f"  Choosing journey with matching finished date: {date_finished}")
                chosen = match
            else:
                self.log("  No matching finished date; using the first journey")

        if chosen.get("id") is None:
            self.log("  ⚠️ Read journey has no id; skipping")
            return None

        return {
            "journey_id": chosen["id"],
            "started_at": chosen.get("started_at"),
            "finished_at": chosen.get("finished_at"),
        }

    def update_reading_date(self, journey_id, date_started, date_finished):
        """Update the reading date for a book on Hardcover."""
        if self.dry_run:
            self.log(
                f"  🔎 [dry-run] Would set journey {journey_id} to "
                f"{date_started} → {date_finished}"
            )
            return True

        mutation = """
            mutation updateReadingDate ($journeyId: Int!, $dateStarted: date!, $dateFinished: date!) {
                 update_user_book_read(
                     id: $journeyId
                     object: {started_at: $dateStarted, finished_at: $dateFinished}
                   ) {
                     id
                     user_book_read {
                       finished_at
                       started_at
                     }
                   }
                 }
        """

        variables = {
            "journeyId": int(journey_id),
            "dateStarted": date_started,
            "dateFinished": date_finished,
        }

        _payload, success = self._make_request_with_retry(mutation, variables)
        return success


def _retry_after_seconds(response, default):
    """Read a Retry-After header, falling back to `default`."""
    try:
        return max(0, int(response.headers.get("Retry-After", "")))
    except (TypeError, ValueError):
        return default


def normalize_api_key(api_key):
    """Ensure the API key carries the 'Bearer ' prefix the API expects."""
    api_key = (api_key or "").strip()
    if api_key and not api_key.lower().startswith("bearer "):
        return f"Bearer {api_key}"
    return api_key


def load_api_key(api_key_file, logger):
    """Load the API key from a JSON file."""
    try:
        with open(api_key_file, "r", encoding="utf-8") as f:
            data = json.load(f)
    except FileNotFoundError:
        logger.log(f"Error: API key file not found: {api_key_file}")
        logger.log('Create it with: {"api_key": "Bearer your_token_here"}')
        return None
    except (json.JSONDecodeError, OSError) as e:
        logger.log(f"Error loading API key: {e}")
        return None

    if not isinstance(data, dict):
        logger.log(f"Error: {api_key_file} must contain a JSON object with an 'api_key' key.")
        return None

    api_key = (data.get("api_key") or "").strip()
    if not api_key:
        logger.log(f"Error: no non-empty 'api_key' found in {api_key_file}.")
        return None
    return api_key


def format_date(date_str, logger):
    """Convert date from various formats to yyyy-mm-dd format."""
    date_str = (date_str or "").strip()
    if not date_str or date_str.lower() in {"not set", "unknown", "-"}:
        return None

    for fmt in ("%Y-%m-%d", "%m/%d/%y", "%m/%d/%Y", "%b %d, %Y", "%B %d, %Y", "%b %Y", "%B %Y"):
        try:
            return datetime.strptime(date_str, fmt).strftime("%Y-%m-%d")
        except ValueError:
            continue

    logger.log(f"Warning: Could not parse date: {date_str}")
    return None


def process_tsv_file(tsv_file, client, limit=0, delay=1.0):
    """Process a TSV file and update reading dates on Hardcover."""
    rows_seen = 0
    books_updated = 0
    books_unchanged = 0
    books_skipped = 0
    books_failed = 0

    try:
        with open(tsv_file, "r", encoding="utf-8") as tsvfile:
            reader = csv.DictReader(tsvfile, delimiter="\t")

            missing = [c for c in REQUIRED_COLUMNS if c not in (reader.fieldnames or [])]
            if missing:
                client.log(
                    f"Error: {tsv_file} is missing required column(s): {', '.join(missing)}"
                )
                client.log("Regenerate it with parse_goodreads.py.")
                return 1

            if limit > 0:
                client.log(f"\n⚠️ Processing limited to {limit} books (for testing)")

            for row_num, row in enumerate(reader, 1):
                if limit > 0 and rows_seen >= limit:
                    client.log(f"\n⚠️ Reached limit of {limit} books. Stopping.")
                    break

                rows_seen += 1
                try:
                    goodreads_id = (row.get("Goodreads ID") or "").strip()
                    book_title = (row.get("Book Title") or "").strip() or "<untitled>"
                    client.log(f"\n📍Processing row {row_num}: {book_title}")

                    if not goodreads_id:
                        client.log("  ⏭️ Skipping: no Goodreads ID")
                        books_skipped += 1
                        continue

                    date_started = format_date(row.get("Date Started"), client.logger)
                    date_finished = format_date(row.get("Date Read"), client.logger)

                    # Hardcover requires both dates on a read journey. When only
                    # one of the two is known, use it for both ends.
                    if not date_started and not date_finished:
                        client.log("  ⏭️ Skipping: no usable start or finish date")
                        books_skipped += 1
                        continue
                    date_started = date_started or date_finished
                    date_finished = date_finished or date_started

                    if date_finished < date_started:
                        client.log(
                            f"  ⚠️ Finish date {date_finished} precedes start date "
                            f"{date_started}; skipping"
                        )
                        books_skipped += 1
                        continue

                    journey = client.find_book_by_goodreads_id(goodreads_id, date_finished)
                    if not journey:
                        client.log(f"  ❌ Book not found on Hardcover: {book_title}")
                        books_skipped += 1
                        continue

                    if (
                        journey["started_at"] == date_started
                        and journey["finished_at"] == date_finished
                    ):
                        client.log("  ✔️ Already up to date; nothing to change")
                        books_unchanged += 1
                        continue

                    client.log(
                        f"  Updating {journey['started_at']} → {journey['finished_at']} "
                        f"to {date_started} → {date_finished}"
                    )
                    if client.update_reading_date(
                        journey["journey_id"], date_started, date_finished
                    ):
                        books_updated += 1
                        client.log(
                            f"  ✅ '{book_title}' updated with read dates: "
                            f"{date_started} to {date_finished}"
                        )
                    else:
                        books_failed += 1
                        client.log(f"  ❌ Failed to update reading date for '{book_title}'")

                    # Be respectful to the API.
                    time.sleep(delay)
                except Exception as e:
                    books_failed += 1
                    client.log(f"Error processing row {row_num}: {type(e).__name__}: {e}")
                    client.log(f"Row data: {row}")
                    continue

    except FileNotFoundError:
        client.log(f"Error: TSV file not found: {tsv_file}")
        return 1
    except OSError as e:
        client.log(f"Error reading TSV file: {e}")
        return 1

    client.log("\n📊 Summary:")
    client.log(f"Rows processed:          {rows_seen}")
    client.log(f"Books with dates updated:{books_updated:>4}")
    client.log(f"Books already correct:   {books_unchanged}")
    client.log(f"Books skipped:           {books_skipped}")
    client.log(f"Books failed:            {books_failed}")
    if client.dry_run:
        client.log("(dry run — nothing was written to Hardcover)")

    return 1 if books_failed else 0


def main():
    """Main function to handle command line arguments and process the TSV file."""
    args = docopt(__doc__)

    try:
        limit = int(args["--limit"])
    except ValueError:
        print(f"Error: --limit must be an integer, got {args['--limit']!r}")
        return 2
    if limit < 0:
        print("Error: --limit must not be negative.")
        return 2

    try:
        delay = float(args["--delay"])
    except ValueError:
        print(f"Error: --delay must be a number, got {args['--delay']!r}")
        return 2
    if delay < 0:
        print("Error: --delay must not be negative.")
        return 2

    with Logger(log_to_file=bool(args["--log"])) as logger:
        logger.log("Starting script...")
        if args["--dry-run"]:
            logger.log("🔎 Dry run: no changes will be written to Hardcover.")

        logger.log(f"Loading API key from: {args['--api-key']} ...")
        api_key = load_api_key(args["--api-key"], logger)
        if not api_key:
            logger.log("Failed to load API key. Exiting.")
            return 1
        logger.log("API key loaded successfully")

        client = HardcoverClient(api_key, logger=logger, dry_run=bool(args["--dry-run"]))
        logger.log(f"Processing TSV file: {args['<tsv_file>']}")
        exit_code = process_tsv_file(args["<tsv_file>"], client, limit, delay)
        logger.log("\n👍️ Script completed.")
        return exit_code


if __name__ == "__main__":
    sys.exit(main())
